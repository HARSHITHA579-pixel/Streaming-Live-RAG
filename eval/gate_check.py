"""
Evaluation Gate Checker for Streaming RAG

================================================================================
RESPONSIBILITY:
- Validate automated quality and architectural compliance criteria (Gates G1 through G8)
  from session telemetry logs and evaluation benchmark replay results.
- Compute quantitative gate metrics:
    - G1 (Partial Streaming): Incomplete transcript is held/WAITed, no premature retrieval, stable completion proceeds.
    - G2 (Single Intent): Single intent is identified, retrieval occurs, answer is produced.
    - G3 (Multi-Intent Identification & Minimum Evidence): Subqueries decomposed, independent retrieval, evidence merged/deduplicated.
    - G4 (Session Refinement): Refinement detected, delta retrieval performed, answer version increments, state preserved.
    - G5 (No Retrieval Bypass): Conversational turn does not trigger corpus retrieval, response produced directly.
    - G6 (Unsupported Query Uncertainty): Non-corpus query surfaces uncertainty, no fabricated grounded claims.
    - G7 (Citation Grounding): Grounded claims have valid citations tied to retrieved corpus chunks.
    - G8 (Latency Observability): Real latencies measured and recorded across telemetry events.

INPUTS:
- Evaluation results from `eval/results/` generated by `eval/replay_harness.py`.
- Session telemetry JSONL files from `logs/`.

OUTPUTS:
- Gate compliance scorecard (PASS/FAIL per gate with detailed metrics).
- CLI exit code 0 on all gates passing, 1 on any gate failure.

CONNECTED COMPONENTS:
- `eval/replay_harness.py`: Generates the replay results and session telemetry.
- `app.telemetry`: Defines the JSONL schema parsed during gate evaluation.
================================================================================
"""

import sys
import json
import asyncio
from pathlib import Path
from typing import Dict, List, Any, Optional
from dataclasses import dataclass, asdict

# Ensure workspace root is in sys.path
workspace_root = Path(__file__).resolve().parent.parent
if str(workspace_root) not in sys.path:
    sys.path.insert(0, str(workspace_root))

from eval.replay_harness import StreamingReplayHarness, ReplaySessionResult


@dataclass
class GateResult:
    """Represents the compliance result for a specific evaluation gate."""
    gate_id: str  # "G1", "G2", "G3", "G4", "G5", "G6", "G7", "G8"
    gate_name: str
    passed: bool
    score: float
    threshold: float
    details: Dict[str, Any]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class GateChecker:
    """
    Evaluates pipeline telemetry and replay outputs against architectural benchmark gates G1 through G8.
    """

    def __init__(self, logs_dir: str = "logs", results_dir: str = "eval/results"):
        self.logs_dir = Path(logs_dir)
        self.results_dir = Path(results_dir)

    def load_session_telemetry(self, session_id: str) -> List[Dict[str, Any]]:
        """Parses JSONL events for a session."""
        log_path = self.logs_dir / f"session_{session_id}.jsonl"
        if not log_path.exists():
            return []

        events: List[Dict[str, Any]] = []
        try:
            with open(log_path, "r", encoding="utf-8") as f:
                for line in f:
                    line_clean = line.strip()
                    if line_clean:
                        events.append(json.loads(line_clean))
        except Exception:
            pass
        return events

    def load_replay_results(self) -> Dict[str, Any]:
        """Loads aggregate replay results or individual scenario results."""
        agg_file = self.results_dir / "replay_results.json"
        if agg_file.exists():
            try:
                with open(agg_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    results_map: Dict[str, Any] = {}
                    for item in data.get("results", []):
                        results_map[item.get("scenario", "")] = item
                    return results_map
            except Exception:
                pass

        # Fallback: load individual json files
        results_map = {}
        for fpath in self.results_dir.glob("*.json"):
            if fpath.name == "replay_results.json":
                continue
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    scen_data = json.load(f)
                    results_map[scen_data.get("scenario", fpath.stem)] = scen_data
            except Exception:
                pass
        return results_map

    def check_g1_partial_streaming(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G1 — Partial Streaming:
        - Incomplete transcript is held/WAITed (T0 unstable)
        - No premature retrieval on incomplete buffer
        - Stable completion proceeds to retrieval and answer
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            t0_unstable_waited = checks.get("partial_t0_unstable", False)
            no_premature_retrieval = checks.get("partial_no_retrieval", False)
            completion_proceeded = checks.get("completion_retrieval", False) and checks.get("completion_answer", False)
            passed = bool(t0_unstable_waited and no_premature_retrieval and completion_proceeded)
            details = {
                "t0_unstable_waited": t0_unstable_waited,
                "no_premature_retrieval": no_premature_retrieval,
                "completion_retrieval": checks.get("completion_retrieval", False),
                "completion_answer": checks.get("completion_answer", False)
            }
        elif telemetry_events:
            t0_events = [e for e in telemetry_events if e.get("event") == "T0_GATE"]
            wait_events = [e for e in t0_events if e.get("decision_action") == "WAIT" or not e.get("is_stable", True)]
            proceed_events = [e for e in t0_events if e.get("decision_action") == "PROCEED" or e.get("is_stable", False)]
            passed = len(wait_events) > 0 and len(proceed_events) > 0
            details = {
                "t0_wait_events": len(wait_events),
                "t0_proceed_events": len(proceed_events)
            }

        return GateResult(
            gate_id="G1",
            gate_name="Partial Streaming",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g2_single_intent(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G2 — Single Intent:
        - Single intent identified
        - Retrieval occurs
        - Grounded answer produced
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            single_intent = checks.get("single_subquery", False)
            retrieval_ok = checks.get("retrieval_occurred", False)
            answer_ok = checks.get("answer_produced", False)
            passed = bool(single_intent and retrieval_ok and answer_ok and replay_result.get("passed", False))
            details = {
                "single_subquery": single_intent,
                "retrieval_calls": replay_result.get("retrieval_calls", 0),
                "retrieved_chunks": replay_result.get("retrieved_chunks", 0),
                "answer_version": replay_result.get("answer_version", 0)
            }
        elif telemetry_events:
            t1_events = [e for e in telemetry_events if e.get("event") == "T1_DECISION"]
            ret_events = [e for e in telemetry_events if e.get("event") == "RETRIEVAL"]
            passed = (
                len(t1_events) > 0 and
                len(t1_events[0].get("sub_queries", [])) == 1 and
                len(ret_events) > 0 and
                ret_events[0].get("evidence_count", 0) > 0
            )
            details = {"t1_events": len(t1_events), "ret_events": len(ret_events)}

        return GateResult(
            gate_id="G2",
            gate_name="Single Intent",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g3_multi_intent(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G3 — Multi-Intent Identification:
        - Multiple intents decomposed (sub_queries >= 2)
        - Retrieval occurs for sub-queries
        - Evidence merged and deduplicated with minimum evidence guarantee
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            decomposed = checks.get("multi_subqueries_decomposed", False)
            retrieved = checks.get("retrieval_occurred", False)
            citations = checks.get("citations_in_answer", False)
            passed = bool(decomposed and retrieved and citations and replay_result.get("passed", False))
            details = {
                "subqueries_decomposed": decomposed,
                "retrieved_chunks": replay_result.get("retrieved_chunks", 0),
                "citations_present": replay_result.get("citations_present", False)
            }
        elif telemetry_events:
            t1_events = [e for e in telemetry_events if e.get("event") == "T1_DECISION"]
            ret_events = [e for e in telemetry_events if e.get("event") == "RETRIEVAL"]
            subq_count = len(t1_events[0].get("sub_queries", [])) if t1_events else 0
            ev_count = ret_events[0].get("evidence_count", 0) if ret_events else 0
            passed = subq_count >= 2 and ev_count >= 2
            details = {"sub_query_count": subq_count, "evidence_count": ev_count}

        return GateResult(
            gate_id="G3",
            gate_name="Multi-Intent Identification",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g4_refinement(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G4 — Session Refinement:
        - Refinement is recognized (is_refine == True)
        - Delta retrieval occurs
        - Answer version increments from 1 to 2
        - State context preserved
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            v1_ok = checks.get("turn1_version_1", False)
            is_refine_ok = checks.get("turn2_is_refine", False)
            v2_ok = checks.get("turn2_version_2", False)
            passed = bool(v1_ok and is_refine_ok and v2_ok and replay_result.get("passed", False))
            details = {
                "turn1_version_1": v1_ok,
                "turn2_is_refine": is_refine_ok,
                "final_answer_version": replay_result.get("answer_version", 0)
            }
        elif telemetry_events:
            t1_events = [e for e in telemetry_events if e.get("event") == "T1_DECISION"]
            refine_events = [e for e in t1_events if e.get("is_refine", False)]
            passed = len(refine_events) > 0
            details = {"refine_decision_events": len(refine_events)}

        return GateResult(
            gate_id="G4",
            gate_name="Session Refinement",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g5_no_retrieval(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G5 — No Retrieval:
        - Conversational / non-corpus utterance bypasses retrieval (should_retrieve == False)
        - 0 retrieval calls
        - Answer produced directly
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            should_ret_false = checks.get("should_retrieve_false", False)
            no_ret_event = checks.get("no_retrieval_event", False)
            ans_ok = checks.get("answer_produced", False)
            passed = bool(should_ret_false and no_ret_event and ans_ok and replay_result.get("passed", False))
            details = {
                "should_retrieve_false": should_ret_false,
                "retrieval_calls": replay_result.get("retrieval_calls", 0),
                "answer_produced": ans_ok
            }
        elif telemetry_events:
            t1_events = [e for e in telemetry_events if e.get("event") == "T1_DECISION"]
            ret_events = [e for e in telemetry_events if e.get("event") == "RETRIEVAL"]
            passed = len(t1_events) > 0 and not t1_events[0].get("should_retrieve", True) and len(ret_events) == 0
            details = {"retrieval_events_count": len(ret_events)}

        return GateResult(
            gate_id="G5",
            gate_name="No Retrieval",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g6_unsupported_query(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G6 — Unsupported Query:
        - Query outside corpus surfaces uncertainty
        - No fabricated grounded claims
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            uncertainty_surfaced = checks.get("uncertainty_surfaced", False)
            no_fabricated = checks.get("no_fabricated_claims", False)
            passed = bool(uncertainty_surfaced and no_fabricated and replay_result.get("passed", False))
            details = {
                "uncertainty_surfaced": uncertainty_surfaced,
                "uncertainty_present_in_result": replay_result.get("uncertainty_present", False)
            }
        elif telemetry_events:
            verify_events = [e for e in telemetry_events if e.get("event") == "CLAIM_VERIFY"]
            unsupported_claims = [e for e in verify_events if e.get("claim_verification_result") == "UNSUPPORTED"]
            passed = len(unsupported_claims) >= 0  # no fabrication
            details = {"unsupported_claims_caught": len(unsupported_claims)}

        return GateResult(
            gate_id="G6",
            gate_name="Unsupported Query",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g7_citation_grounding(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G7 — Citation Grounding:
        - Grounded claims include valid citations [DOC: ... | Section: ... | Chunk: ...]
        - Citations correspond to retrieved corpus evidence
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            cites_present = checks.get("citations_present", False)
            cites_valid = checks.get("citation_format_valid", False)
            passed = bool(cites_present and cites_valid and replay_result.get("passed", False))
            details = {
                "citations_present": cites_present,
                "citation_format_valid": cites_valid
            }
        elif telemetry_events:
            synth_events = [e for e in telemetry_events if e.get("event") == "SYNTHESIS"]
            cites_gen = synth_events[0].get("citations_generated", 0) if synth_events else 0
            passed = cites_gen > 0
            details = {"citations_generated": cites_gen}

        return GateResult(
            gate_id="G7",
            gate_name="Citation Grounding",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def check_g8_latency(
        self,
        replay_result: Optional[Dict[str, Any]] = None,
        telemetry_events: Optional[List[Dict[str, Any]]] = None
    ) -> GateResult:
        """
        G8 — Latency Observability:
        - Latency is recorded across T0, T1, retrieval, synthesis, verification, and E2E
        - Reports measured values rather than arbitrary thresholds
        """
        passed = False
        details: Dict[str, Any] = {}

        if replay_result:
            checks = replay_result.get("checks", {})
            latency_measured = checks.get("latency_measured", False)
            passed = bool(latency_measured and replay_result.get("latency_ms") is not None)
            details = {
                "latency_measured": latency_measured,
                "measured_e2e_latency_ms": replay_result.get("latency_ms")
            }
        elif telemetry_events:
            e2e_events = [e for e in telemetry_events if e.get("event") in ("E2E", "e2e")]
            lat = e2e_events[0].get("total_latency_ms") if e2e_events else None
            passed = lat is not None
            details = {"measured_e2e_latency_ms": lat}

        return GateResult(
            gate_id="G8",
            gate_name="Latency Observability",
            passed=passed,
            score=1.0 if passed else 0.0,
            threshold=1.0,
            details=details
        )

    def evaluate_all_gates(self, results: Optional[Dict[str, Any]] = None) -> Dict[str, GateResult]:
        """
        Evaluates all 8 benchmark gates across the replay results.
        """
        if results is None:
            results = self.load_replay_results()

        gate_evaluators = {
            "G1": (self.check_g1_partial_streaming, "partial_streaming"),
            "G2": (self.check_g2_single_intent, "single_intent"),
            "G3": (self.check_g3_multi_intent, "multi_intent"),
            "G4": (self.check_g4_refinement, "refinement"),
            "G5": (self.check_g5_no_retrieval, "no_retrieval"),
            "G6": (self.check_g6_unsupported_query, "unsupported_query"),
            "G7": (self.check_g7_citation_grounding, "citation_grounding"),
            "G8": (self.check_g8_latency, "latency")
        }

        gate_results: Dict[str, GateResult] = {}
        for gate_id, (checker_fn, scenario_key) in gate_evaluators.items():
            scen_res = results.get(scenario_key)
            telemetry: Optional[List[Dict[str, Any]]] = None
            if scen_res and "session_id" in scen_res:
                telemetry = self.load_session_telemetry(scen_res["session_id"])
            gate_results[gate_id] = checker_fn(scen_res, telemetry)

        return gate_results


def main() -> int:
    checker = GateChecker()
    results = checker.load_replay_results()

    # If results are missing, run replay harness first
    if not results or len(results) < 8:
        print("Replay results not found or incomplete. Executing StreamingReplayHarness...")
        harness = StreamingReplayHarness()
        asyncio.run(harness.run_all_transcripts())
        results = checker.load_replay_results()

    gate_results = checker.evaluate_all_gates(results)

    print("=" * 65)
    print("STREAMING RAG EVALUATION GATE COMPLIANCE SCORECARD")
    print("=" * 65)
    print(f"{'Gate ID':<8} {'Gate Name':<32} {'Status':<8} {'Details'}")
    print("-" * 65)

    all_passed = True
    for gate_id, gr in gate_results.items():
        status = "PASS" if gr.passed else "FAIL"
        if not gr.passed:
            all_passed = False
        detail_str = ", ".join(f"{k}={v}" for k, v in gr.details.items())
        print(f"{gr.gate_id:<8} {gr.gate_name:<32} {status:<8} {detail_str}")

    print("=" * 65)
    passed_count = sum(1 for gr in gate_results.values() if gr.passed)
    total_gates = len(gate_results)
    print(f"Overall Gate Result: {passed_count}/{total_gates} PASS")
    print("=" * 65)

    return 0 if all_passed else 1


if __name__ == "__main__":
    sys.exit(main())
